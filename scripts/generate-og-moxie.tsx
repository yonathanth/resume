/**
 * Regenerates src/lib/og/moxie-art.generated.ts — Moxie's resting artwork as
 * an SVG string, for share images (next/og can't run her React component, so
 * it gets a picture). Run after changing components/moxie/MoxieArt.tsx:
 *
 *   npx tsx scripts/generate-og-moxie.tsx
 */
import fs from "node:fs";
import path from "node:path";
import React from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { MoxieArt } from "../src/components/moxie/MoxieArt";

const svg = renderToStaticMarkup(<MoxieArt idPrefix="og" decorative showShadow={false} />);
const out = path.join(__dirname, "../src/lib/og/moxie-art.generated.ts");
fs.writeFileSync(
  out,
  `// Generated by scripts/generate-og-moxie.tsx — don't edit by hand.\n` +
    `// Moxie's resting pose (MoxieArt), every prop hidden until poseSvg() shows it.\n` +
    `export const MOXIE_SVG = ${JSON.stringify(svg)};\n`
);
console.log(`Wrote ${path.relative(process.cwd(), out)} (${svg.length} chars)`);
