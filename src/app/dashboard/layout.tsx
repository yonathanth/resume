"use client";

import React, { useState } from "react";
import { usePathname } from "next/navigation";
import { DashboardSidebar, DashboardTab } from "@/components/dashboard/DashboardSidebar";
import { DashboardProvider, useDashboard } from "@/components/dashboard/DashboardContext";
import { CvEditorWorkspace } from "@/components/dashboard/create-flow/CvEditorWorkspace";
import { useRefreshSubscriptionStatus, useSubscriptionStatus } from "@/hooks/use-subscription";
import { useMe } from "@/hooks/use-auth";
import { OnboardingModal } from "@/components/dashboard/OnboardingModal";
import { MoxieMoment } from "@/components/moxie";
import { AuthGuard } from "@/components/AuthGuard";
import { DashboardTopBar } from "@/components/dashboard/DashboardTopBar";
import { QuickTour } from "@/components/dashboard/QuickTour";
import { QuickLinkLauncher } from "@/components/dashboard/QuickLinkLauncher";

// The sidebar's pages, listed in the top bar's menu on small screens.
const MOBILE_NAV_ITEMS: { href: string; label: string }[] = [
  { href: "/dashboard", label: "The Builder" },
  { href: "/dashboard/career-profiles", label: "Career Profiles" },
  { href: "/dashboard/past-projects", label: "Past Projects" },
  { href: "/dashboard/templates", label: "Templates" },
];

// Each page's title, shown only in the top bar.
const PAGE_TITLES: Record<DashboardTab, string> = {
  builder: "The Builder",
  "career-profiles": "Career Profiles",
  "past-projects": "Past Projects",
  templates: "Templates",
  settings: "Account Settings",
  help: "Help",
  upgrade: "Upgrade",
};
const TAB_HREFS: Record<DashboardTab, string> = {
  builder: "/dashboard",
  "career-profiles": "/dashboard/career-profiles",
  "past-projects": "/dashboard/past-projects",
  templates: "/dashboard/templates",
  settings: "/dashboard/settings",
  help: "/dashboard/help",
  upgrade: "/dashboard/upgrade",
};

function EditorOverlay() {
  const { activeEditingCv, setActiveEditingCv, updateDraftFromSavedCv } = useDashboard();
  const refreshSubscriptionStatus = useRefreshSubscriptionStatus();
  if (!activeEditingCv) return null;

  return (
    <CvEditorWorkspace
      initialData={activeEditingCv}
      onBack={() => setActiveEditingCv(null)}
      onSave={(savedCv) => {
        // Same helper the dedicated editor route and BuilderView use — it
        // pairs the optimistic draft patch with a CV_DRAFTS_QUERY_KEY
        // invalidation, so the dashboard's list reflects the real saved
        // state once that refetch resolves, not just the local guess.
        updateDraftFromSavedCv(savedCv);
        // A generation may have just spent a free tab use — refresh so the
        // dashboard's Pro/free-usage state isn't left stale.
        refreshSubscriptionStatus();
        setActiveEditingCv(null);
      }}
    />
  );
}

function DashboardChrome({ children }: { children: React.ReactNode }) {
  const pathname = usePathname();
  const { activeEditingCv } = useDashboard();
  const [isSidebarExpanded, setIsSidebarExpanded] = useState(false);
  const [tourOpen, setTourOpen] = useState(false);
  // Set when someone finishes onboarding: Moxie welcomes them by name.
  const [welcome, setWelcome] = useState<string | null>(null);
  const { data: subscription } = useSubscriptionStatus();
  const isPro = subscription?.isPro ?? false;
  const { data: me } = useMe();

  const activeTab: DashboardTab = pathname.startsWith("/dashboard/career-profiles")
    ? "career-profiles"
    : pathname.startsWith("/dashboard/past-projects")
      ? "past-projects"
      : pathname.startsWith("/dashboard/templates")
        ? "templates"
        : pathname.startsWith("/dashboard/settings")
          ? "settings"
          : pathname.startsWith("/dashboard/help")
            ? "help"
            : pathname.startsWith("/dashboard/upgrade")
              ? "upgrade"
              : "builder";

  // While editing a CV just generated by a create/tailor/enhance flow, the
  // editor takes over the full viewport as an overlay — hoisted here so it
  // works no matter which page triggered it.
  if (activeEditingCv) {
    return <EditorOverlay />;
  }

  // The dedicated CV editor page (/dashboard/editor/[id], reached via any
  // "Edit" action) also takes over the full viewport — it renders its own
  // header/layout, so skip the sidebar chrome here rather than nesting it.
  if (pathname.startsWith("/dashboard/editor/")) {
    return <>{children}</>;
  }

  return (
    <div className="h-screen w-full overflow-hidden bg-[#fbfbfb] text-neutral-900 flex font-sans antialiased relative">
      {/* Desktop Sidebar (Collapsible & Expandable, Fixed in Viewport) */}
      <div className="hidden md:block shrink-0 h-full z-30">
        <DashboardSidebar
          activeTab={activeTab}
          isExpanded={isSidebarExpanded}
          onToggleExpanded={() => setIsSidebarExpanded(!isSidebarExpanded)}
        />
      </div>

      {/* Main Content Area (Independent scroll while sidebar remains fixed) */}
      <div className="flex-1 min-w-0 h-full flex flex-col">
        <DashboardTopBar
          title={PAGE_TITLES[activeTab]}
          onStartTour={() => setTourOpen(true)}
          mobileNavItems={MOBILE_NAV_ITEMS}
          activeHref={TAB_HREFS[activeTab]}
          isPro={isPro}
        />
        {/* Main content scrolls on its own; the sidebar and top bar stay put. */}
        <main className="flex-1 min-h-0 overflow-y-auto">{children}</main>
      </div>

      {tourOpen && <QuickTour onClose={() => setTourOpen(false)} />}

      {/* First-run details for a brand-new account. `=== false` so an older
          API that doesn't send the flag never shows it. */}
      {me && me.onboardingCompleted === false && <OnboardingModal me={me} onFinished={(firstName) => setWelcome(firstName)} />}
      {/* What a quick link (/go/...) asked for, once nothing else is over the page. */}
      <QuickLinkLauncher ready={Boolean(me) && me?.onboardingCompleted !== false && welcome === null && !activeEditingCv} />
      {welcome !== null && (
        <MoxieMoment
          animation="onboarded"
          message={welcome ? `Welcome aboard, ${welcome}!` : "Welcome aboard!"}
          onDone={() => setWelcome(null)}
        />
      )}
    </div>
  );
}

export default function DashboardLayout({ children }: { children: React.ReactNode }) {
  return (
    <AuthGuard>
      <DashboardProvider>
        <DashboardChrome>{children}</DashboardChrome>
      </DashboardProvider>
    </AuthGuard>
  );
}
